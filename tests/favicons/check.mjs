/* node --experimental-strip-types tests/favicons/check.mjs */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {faviconCandidates, faviconRoute, faviconBlob, FAVICON_LIMIT} from '../../ui/src/browser/favicon.ts';
const origin='https://content.example';
const calls=[];
const query=async m=>{calls.push(m);return m.type==='zl:decodeRoutes'?{ok:true,dests:['https://site.example/real-icon.png']}:{ok:true,url:'/real-icon.png?zlNavh=opaque123456789'};};
assert.deepEqual(await faviconCandidates('https://site.example/path/','https://content.example/pic?zlNavh=opaque123456789',origin,query),['https://site.example/real-icon.png','https://site.example/favicon.ico']);
assert.equal(calls[0].type,'zl:decodeRoutes');
assert.deepEqual(await faviconCandidates('https://site.example/a','/icon.svg',origin,query),['https://site.example/icon.svg','https://site.example/favicon.ico']);
assert.deepEqual(await faviconCandidates('https://site.example/a','https://content.example/__zl_navh__/expired',origin,async()=>({dests:[null]})),['https://site.example/favicon.ico']);
assert.deepEqual(await faviconCandidates('https://site.example/a','javascript:alert(1)',origin,query),['https://site.example/favicon.ico']);
assert.deepEqual(await faviconCandidates('https://site.example/a','https://username:password@site.example/icon.png',origin,query),['https://site.example/favicon.ico']);
assert.equal(await faviconRoute('https://site.example/icon.png',origin,query,()=>'/zl/fallback'),'https://content.example/real-icon.png?zlNavh=opaque123456789');
assert.equal(await faviconRoute('https://site.example/icon.png',origin,async()=>({ok:true,url:'https://evil.example/direct'}),()=>'/zl/fallback'),'https://content.example/zl/fallback');
assert.equal(await faviconRoute('https://site.example/icon.png',origin,async()=>null,()=> 'https://evil.example/direct'),null);
assert.equal(await faviconBlob(new Response('<html>error</html>',{headers:{'content-type':'text/html'}})),null);
assert.equal(await faviconBlob(new Response(new Uint8Array(0),{headers:{'content-type':'image/png'}})),null);
assert.equal(await faviconBlob(new Response(new Uint8Array(FAVICON_LIMIT+1),{headers:{'content-type':'image/png'}})),null);
assert.equal((await faviconBlob(new Response(new Uint8Array([1,2,3]),{headers:{'content-type':'IMAGE/PNG; charset=binary'}}))).size,3);
const server=readFileSync(new URL('../../server/bin/server/src/main.rs',import.meta.url),'utf8');
const helper=server.split('/* #203 icon fetch begin */')[1].split('/* #203 icon fetch end */')[0];
const seen=[];
const nativeFetch=async(url,opts)=>{seen.push([url,opts]);return new Response(new Uint8Array([1,2,3]),{headers:{'content-type':'image/png'}});};
const fetchIcon=new Function('location','fetch',helper+';return fetchIcon;')({origin},nativeFetch);
assert.equal((await fetchIcon('https://elsewhere.example/zl/token')).ok,false);
assert.equal((await fetchIcon('/healthz')).ok,false);
assert.equal((await fetchIcon('/icon.png?zlNavh=short')).ok,false);
assert.equal((await fetchIcon(null)).ok,false);
assert.equal(seen.length,0,'refused URLs must not be fetched');
const reply=await fetchIcon('/icon.png?zlNavh=opaque123456789');
assert.equal(reply.ok,true);
assert.deepEqual([...new Uint8Array(reply.bytes)],[1,2,3]);
assert.equal(seen[0][1].redirect,'error');
assert.equal(seen[0][1].credentials,'omit');
const fetchBad=new Function('location','fetch',helper+';return fetchIcon;')({origin},async()=>new Response('<html>wrong</html>',{headers:{'content-type':'text/html'}}));
assert.equal((await fetchBad('/zl/token')).ok,false);
const fetchBig=new Function('location','fetch',helper+';return fetchIcon;')({origin},async()=>new Response(new Uint8Array(400001),{headers:{'content-type':'image/png'}}));
assert.equal((await fetchBig('/zl/token')).ok,false);
assert.match(server,/ev\.source !== parent \|\| ev\.origin !== appOrigin/);
console.log('favicons: worker decode/mint, origin-only routes, no native upstream, MIME and streamed bounds passed');
